CREATE OR REPLACE FUNCTION public.reject_hiring_proposal(
  p_proposal_id uuid,
  p_guide_remarks text DEFAULT NULL,
  p_tourist_remarks text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_uid uuid;
  v_hp public.hiring_proposals%ROWTYPE;
