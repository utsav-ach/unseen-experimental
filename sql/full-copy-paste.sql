RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    auth_user auth.users%ROWTYPE;
    profile_data public.profiles%ROWTYPE;
BEGIN
    -- Get auth user
    SELECT *
    INTO auth_user
    FROM auth.users
    WHERE id = target_id;

    IF auth_user IS NULL THEN
        RETURN jsonb_build_object(
            'profile', NULL,
            'is_onboarding_done', false,
            'is_auth_verified', false
        );
