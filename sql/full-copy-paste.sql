CREATE OR REPLACE FUNCTION public.clean_text(
  p_value text,
  p_field_name text
)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  v_text text;
BEGIN
  v_text := NULLIF(TRIM(p_value), '');
  IF v_text IS NULL THEN
    RAISE EXCEPTION '% is required and cannot be empty.', COALESCE(NULLIF(TRIM(p_field_name), ''), 'Field');
  END IF;
  RETURN v_text;
END;
$$;

