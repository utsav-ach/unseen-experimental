    INSERT INTO public.suspended_guides (guide_id, reason, admin_id, created_at)
    VALUES (p_guide_id, v_reason, v_admin_id, now());
  END IF;

  RETURN jsonb_build_object(
    'guide_id', p_guide_id,
    'suspended', v_status,
    'reason', v_reason
  );
END;
$$;

